-- Run this script in the Supabase SQL Editor before using the platform.

create extension if not exists pgcrypto;

insert into storage.buckets (id, name, public)
values ('spatial-uploads', 'spatial-uploads', false)
on conflict (id) do nothing;

insert into storage.buckets (id, name, public)
values ('verification-documents', 'verification-documents', false)
on conflict (id) do nothing;

drop policy if exists "Authenticated users can upload spatial files" on storage.objects;
create policy "Authenticated users can upload spatial files"
on storage.objects for insert
to authenticated
with check (bucket_id = 'spatial-uploads');

drop policy if exists "Authenticated users can view spatial files" on storage.objects;
create policy "Authenticated users can view spatial files"
on storage.objects for select
to authenticated
using (bucket_id = 'spatial-uploads');

drop policy if exists "Authenticated users can upload verification documents" on storage.objects;
create policy "Authenticated users can upload verification documents"
on storage.objects for insert
to authenticated
with check (bucket_id = 'verification-documents');

drop policy if exists "Authenticated users can view verification documents" on storage.objects;
create policy "Authenticated users can view verification documents"
on storage.objects for select
to authenticated
using (bucket_id = 'verification-documents');

create table if not exists public.user_registrations (
  id uuid primary key default gen_random_uuid(),
  user_id uuid references auth.users(id) on delete set null,
  registration_type text not null check (registration_type in ('student', 'professional')),
  full_name text not null,
  email text not null,
  institution text,
  program text,
  student_id text,
  organization_name text,
  organization_type text,
  occupation text,
  role text,
  phone text,
  verification_document_url text,
  status text not null default 'pending_review' check (status in ('pending_review', 'approved', 'rejected')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.user_registrations enable row level security;

drop policy if exists "Users can insert their own registration" on public.user_registrations;
create policy "Users can insert their own registration"
on public.user_registrations for insert
to authenticated
with check (user_id = auth.uid() or user_id is null);

drop policy if exists "Users can view their own registration" on public.user_registrations;
create policy "Users can view their own registration"
on public.user_registrations for select
to authenticated
using (user_id = auth.uid());

drop policy if exists "Users can update their own registration" on public.user_registrations;
create policy "Users can update their own registration"
on public.user_registrations for update
to authenticated
using (user_id = auth.uid())
with check (user_id = auth.uid());

create table if not exists public.data_requests (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('request', 'share')),
  direction text not null check (direction in ('incoming', 'outgoing')),
  sender_id uuid not null references auth.users(id),
  recipient text not null,
  subject text not null,
  details text not null,
  file_path text,
  status text not null default 'open',
  created_at timestamptz not null default now()
);

alter table public.data_requests enable row level security;

drop policy if exists "Authenticated users can view exchange records" on public.data_requests;
create policy "Authenticated users can view exchange records"
on public.data_requests for select
to authenticated
using (true);

drop policy if exists "Authenticated users can create exchange records" on public.data_requests;
create policy "Authenticated users can create exchange records"
on public.data_requests for insert
to authenticated
with check (sender_id = auth.uid());